// Uploaded menu photos: allowed formats and the size cap. The dashboard shrinks
// the photo in the browser first, so this is a safety limit, not the normal size.
export const MAX_MENU_IMAGE_BYTES = 2 * 1024 * 1024;

// Decides the real format from the file's first bytes (never from the
// client-supplied name or content type). Returns null for anything that is not
// a JPEG, PNG or WebP image.
export function detectImageMime(buf: Buffer): string | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) {
    return 'image/jpeg';
  }
  if (
    buf.length >= 8 &&
    buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47 &&
    buf[4] === 0x0d && buf[5] === 0x0a && buf[6] === 0x1a && buf[7] === 0x0a
  ) {
    return 'image/png';
  }
  if (
    buf.length >= 12 &&
    buf.toString('ascii', 0, 4) === 'RIFF' &&
    buf.toString('ascii', 8, 12) === 'WEBP'
  ) {
    return 'image/webp';
  }
  return null;
}
